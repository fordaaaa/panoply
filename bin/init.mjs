#!/usr/bin/env node
// Installs the panoply commands and skills into whichever agent this project uses.
//
//   node ~/panoply/bin/init.mjs                 detect the tool and install
//   node ~/panoply/bin/init.mjs --global        install once for every project on this machine
//   node ~/panoply/bin/init.mjs --tool cursor   force one tool
//   node ~/panoply/bin/init.mjs --all           install for every supported tool
//   node ~/panoply/bin/init.mjs --with playwright,context7
//   node ~/panoply/bin/init.mjs --dry-run
//
// Zero dependencies, by design. Nothing here phones home.

import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, cpSync, renameSync } from "node:fs";
import { createInterface } from "node:readline/promises";
import { join, dirname, resolve } from "node:path";
import { homedir } from "node:os";
import { fileURLToPath } from "node:url";

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cwd = resolve(process.cwd());
const home = homedir();
const argv = process.argv.slice(2);

const USAGE = `Installs the panoply commands into whichever agent this project uses.

  node ~/panoply/bin/init.mjs                 detect the tool and install
  node ~/panoply/bin/init.mjs --global        install once for every project on this machine
  node ~/panoply/bin/init.mjs --tool cursor   force one tool (claude-code, opencode, cursor)
  node ~/panoply/bin/init.mjs --all           install for every supported tool
  node ~/panoply/bin/init.mjs --with playwright,context7
  node ~/panoply/bin/init.mjs --dry-run       show what would happen, write nothing
  node ~/panoply/bin/init.mjs --yes           skip the setup questions
  node ~/panoply/bin/init.mjs --help`;

if (argv.includes("--help") || argv.includes("-h")) {
  console.log(USAGE);
  process.exit(0);
}

const flag = (name) => {
  const eq = argv.find((a) => a.startsWith(`--${name}=`));
  if (eq) return eq.slice(name.length + 3);
  const i = argv.indexOf(`--${name}`);
  return i !== -1 ? argv[i + 1] : undefined;
};
const has = (name) => argv.includes(`--${name}`);

// Stamped into every generated file by build.mjs; its presence means "ours".
const MARKER = "GENERATED by build.mjs";

const dryRun = has("dry-run");
const isGlobal = has("global");
const extras = (flag("with") ?? "").split(",").map((s) => s.trim()).filter(Boolean);

// Opt-in servers the onboarding prompt can offer. Kept here (not parsed out of
// servers.json) so each can carry its own setup question.
const OPT_IN = {
  showcase: {
    label: "panoply-showcase — record/capture videos of your session into an exports folder",
    ask: async (rl) => {
      const answer = (await rl.question("  Where should showcase recordings be saved? [~/Videos/panoply] ")).trim();
      return answer || join(home, "Videos", "panoply");
    },
  },
  caveman: {
    label: "panoply-caveman — approximate usage signal for the caveman-compression hook (no secrets, no network)",
  },
};

/**
 * Best-effort GITHUB_MCP_TOKEN check, shown before install rather than only in
 * the easy-to-miss trailing message. Read-only (one GET to the GitHub REST
 * API, not the MCP endpoint) and never blocks install — this is a deliberate,
 * small exception to this file's "nothing here phones home" rule, made
 * because catching a stale token here beats a confusing "upstream 400" later.
 * Runs even under --dry-run/CI since it writes nothing and is purely
 * informational.
 */
async function checkGithubAuth() {
  let servers;
  try { servers = JSON.parse(readFileSync(join(pkgRoot, "mcp", "servers.json"), "utf8")); }
  catch { return; }
  const willInstall = servers.github && (servers.github.profile === "default" || extras.includes("github"));
  if (!willInstall) return;

  const token = process.env.GITHUB_MCP_TOKEN;
  if (!token) {
    console.log(
      "\nGITHUB_MCP_TOKEN is not set. The GitHub MCP server authenticates by header, not OAuth:\n" +
      '  export GITHUB_MCP_TOKEN="$(gh auth token)"\n' +
      "Set it now, or later — see docs/mcp-auth.md. `gh` itself works either way.",
    );
    return;
  }
  try {
    const res = await fetch("https://api.github.com/user", { headers: { Authorization: `Bearer ${token}` } });
    if (res.ok) {
      const user = await res.json();
      console.log(`\n✓ GITHUB_MCP_TOKEN looks valid (authenticated as ${user.login}).`);
    } else if (res.status === 401) {
      console.log(
        '\n✗ GITHUB_MCP_TOKEN looks stale or invalid. Try `export GITHUB_MCP_TOKEN="$(gh auth token)"` again — see docs/mcp-auth.md.',
      );
    }
  } catch {
    // network hiccup during install should never block it — silently skip
  }
}

/**
 * Personalize before anything is written: which opt-in servers to pull in, and
 * whatever each of those needs to know. Silent when stdin isn't a TTY or
 * --yes/--with/--dry-run already answered everything — CI keeps working.
 */
async function onboard() {
  if (!process.stdin.isTTY || dryRun || has("yes")) return;
  const rl = createInterface({ input: process.stdin, output: process.stdout });

  console.log("\nA couple of questions before installing — answer, or just press enter to skip:");
  for (const [name, s] of Object.entries(OPT_IN)) {
    if (extras.includes(name)) continue;
    const want = (await rl.question(`\n  Include ${s.label}? [y/N] `)).trim().toLowerCase();
    if (!["y", "yes"].includes(want)) continue;
    extras.push(name);
    if (!s.ask) continue;
    const value = await s.ask(rl);
    if (name === "showcase") {
      const cfg = join(home, ".panoply", "showcase");
      mkdirSync(cfg, { recursive: true });
      writeFileSync(join(cfg, "config.json"), JSON.stringify({ exports_dir: resolve(value.replace(/^~(?=\/|$)/, home)) }, null, 2) + "\n");
      console.log(`  ✓ saved — recordings will land in ${value}`);
    }
  }
  rl.close();
}

// Every agent here merges a user-level command dir with the project one, so a
// global install covers every project without touching any of them. The MCP
// file differs per scope: project-scope Claude Code reads `.mcp.json`, but
// user-scope lives under `mcpServers` in the app's own `~/.claude.json`.
// Only Claude Code has a `skills` dir: opencode and Cursor have no skills.
const TOOLS = {
  "claude-code": {
    from: ".claude/commands",
    label: "Claude Code",
    project: { to: ".claude/commands", mcp: ".mcp.json", skills: ".claude/skills" },
    global: { to: join(home, ".claude", "commands"), mcp: join(home, ".claude.json"), skills: join(home, ".claude", "skills") },
  },
  opencode: {
    from: ".opencode/commands",
    label: "opencode",
    project: { to: ".opencode/commands", mcp: "opencode.json" },
    global: { to: join(home, ".config", "opencode", "commands"), mcp: join(home, ".config", "opencode", "opencode.json") },
  },
  cursor: {
    from: ".cursor/commands",
    label: "Cursor",
    project: { to: ".cursor/commands", mcp: ".cursor/mcp.json" },
    global: { to: join(home, ".cursor", "commands"), mcp: join(home, ".cursor", "mcp.json") },
  },
};

/** Absolute destinations for the scope we're installing into. */
function target(tool) {
  const t = TOOLS[tool];
  if (isGlobal) return { ...t.global, show: (p) => p.replace(home, "~") };
  return {
    to: join(cwd, t.project.to),
    mcp: join(cwd, t.project.mcp),
    skills: t.project.skills && join(cwd, t.project.skills),
    show: (p) => p.replace(cwd + "/", ""),
  };
}

/** Which agents show signs of use — in this project, or on this machine. */
function detect() {
  const found = [];
  const seen = (...paths) => paths.some((p) => existsSync(p));
  if (isGlobal) {
    if (seen(join(home, ".claude"), join(home, ".claude.json"))) found.push("claude-code");
    if (seen(join(home, ".config", "opencode"))) found.push("opencode");
    if (seen(join(home, ".cursor"))) found.push("cursor");
    return found;
  }
  if (seen(join(cwd, ".claude"), join(cwd, "CLAUDE.md"))) found.push("claude-code");
  if (seen(join(cwd, ".opencode"), join(cwd, "opencode.json"))) found.push("opencode");
  if (seen(join(cwd, ".cursor"))) found.push("cursor");
  return found;
}

function mcpFor(tool) {
  const path = join(pkgRoot, "mcp", "servers.json");
  if (!existsSync(path)) return {};
  const all = JSON.parse(readFileSync(path, "utf8"));
  const out = {};
  for (const [name, s] of Object.entries(all)) {
    if (name.startsWith("$")) continue;
    if (s.profile !== "default" && !extras.includes(name)) continue;
    const isStdio = s.transport === "stdio";
    if (tool === "opencode") {
      out[name] = isStdio
        ? { type: "local", command: [s.command, ...(s.args ?? [])], enabled: true }
        : { type: "remote", url: s.url, enabled: true };
    } else if (tool === "cursor") {
      out[name] = isStdio ? { command: s.command, args: s.args ?? [] } : { url: s.url };
    } else {
      out[name] = isStdio ? { type: "stdio", command: s.command, args: s.args ?? [] } : { type: "http", url: s.url };
    }
  }
  return out;
}

/**
 * Replace a config file without ever leaving a partial one behind.
 *
 * `~/.claude.json` is not ours — it is the running app's live state file, tens
 * of kilobytes of it, rewritten whenever the app feels like it. Writing in
 * place risks a reader seeing a half-written file, and a bad merge would eat
 * settings we never looked at. So: keep a backup, write a sibling temp file,
 * then rename it over the target, which is atomic within a filesystem.
 */
function writeConfig(dest, config) {
  if (dryRun) return;
  mkdirSync(dirname(dest), { recursive: true });
  if (existsSync(dest)) cpSync(dest, `${dest}.panoply-bak`);
  const tmp = `${dest}.panoply-tmp`;
  writeFileSync(tmp, JSON.stringify(config, null, 2) + "\n");
  renameSync(tmp, dest);
}

/** Merge our servers into the existing MCP config without clobbering theirs. */
function installMcp(tool) {
  const { mcp: dest, show } = target(tool);
  const name_ = show(dest);
  const servers = mcpFor(tool);
  if (!Object.keys(servers).length) return null;

  const key = tool === "opencode" ? "mcp" : "mcpServers";
  let config = {};
  if (existsSync(dest)) {
    try { config = JSON.parse(readFileSync(dest, "utf8")); }
    catch { return `! ${name_} is not valid JSON — left it alone, add the servers by hand`; }
  } else if (tool === "opencode") {
    config = { $schema: "https://opencode.ai/config.json" };
  }

  const existing = config[key] ?? {};
  const added = [];
  for (const [name, spec] of Object.entries(servers)) {
    if (name in existing) continue; // never overwrite a server the user configured
    existing[name] = spec;
    added.push(name);
  }
  if (!added.length) return `  ${name_} already has these servers`;

  config[key] = existing;
  writeConfig(dest, config);
  const backed = isGlobal && existsSync(`${dest}.panoply-bak`) ? `  (backup: ${show(dest)}.panoply-bak)` : "";
  return `  ${name_} ← ${added.join(", ")}${backed}`;
}

/**
 * Copy each skill directory (SKILL.md plus bundled files) into the tool's skills
 * dir. Same rule as commands: an existing directory is replaced only when its
 * SKILL.md carries our marker, so a skill the user wrote by hand is never touched.
 */
function installSkills(tool) {
  const { label } = TOOLS[tool];
  const { skills: dest, show } = target(tool);
  if (!dest) return;
  const src = join(pkgRoot, ".claude", "skills");
  if (!existsSync(src)) {
    console.error(`! ${label}: .claude/skills is missing from the package — run \`node build.mjs\` first`);
    return;
  }
  const names = readdirSync(src, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name);

  if (!dryRun) mkdirSync(dest, { recursive: true });
  for (const name of names) {
    const dir = join(dest, name);
    const overwriting = existsSync(dir);
    const skillFile = join(dir, "SKILL.md");
    if (overwriting && !(existsSync(skillFile) && readFileSync(skillFile, "utf8").includes(MARKER))) {
      console.log(`  skipped skill ${name} — you already have your own skill by that name`);
      continue;
    }
    if (!dryRun) cpSync(join(src, name), dir, { recursive: true });
    console.log(`  ${overwriting ? "updated" : "installed"} ${show(dir)}/`);
  }
}

function install(tool) {
  const { from, label } = TOOLS[tool];
  const src = join(pkgRoot, from);
  if (!existsSync(src)) {
    console.error(`! ${label}: ${from} is missing from the package — run \`node build.mjs\` first`);
    return;
  }
  const { to: dest, show } = target(tool);
  const names = readdirSync(src).filter((f) => f.endsWith(".md"));

  console.log(`\n${label}`);
  if (!dryRun) mkdirSync(dest, { recursive: true });
  for (const name of names) {
    const file = join(dest, name);
    const overwriting = existsSync(file);
    if (overwriting && !readFileSync(file, "utf8").includes(MARKER)) {
      console.log(`  skipped ${name} — you already have your own command by that name`);
      continue;
    }
    if (!dryRun) cpSync(join(src, name), file);
    console.log(`  ${overwriting ? "updated" : "installed"} ${show(file)}`);
  }
  installSkills(tool);
  const note = installMcp(tool);
  if (note) console.log(note);
}

// --- main --------------------------------------------------------------------

const cmd = argv[0] && !argv[0].startsWith("-") ? argv[0] : "init";
if (!["init", "install"].includes(cmd)) {
  console.error(`unknown command \`${cmd}\` — usage: node ~/panoply/bin/init.mjs [--tool <name>] [--all] [--with a,b] [--dry-run]`);
  process.exit(1);
}

const forced = flag("tool");
if (forced && !TOOLS[forced]) {
  console.error(`unknown tool \`${forced}\` — one of: ${Object.keys(TOOLS).join(", ")}`);
  process.exit(1);
}

let chosen;
if (forced) chosen = [forced];
else if (has("all")) chosen = Object.keys(TOOLS);
else {
  chosen = detect();
  if (!chosen.length) {
    const where = isGlobal ? "is installed on this machine" : "this project uses";
    const g = isGlobal ? " --global" : "";
    console.log(
      `Couldn't tell which agent ${where}.\n` +
      "Re-run with one of:\n" +
      Object.entries(TOOLS).map(([k, v]) => `  node ~/panoply/bin/init.mjs${g} --tool ${k}   (${v.label})`).join("\n") +
      `\n  node ~/panoply/bin/init.mjs${g} --all\n\n` +
      "Using something else? Copy a file from prompts/ and paste it in.",
    );
    process.exit(0);
  }
}

// Running the project installer inside panoply itself would copy every file
// onto itself; cpSync throws ERR_FS_CP_EINVAL on the first one. A global
// install writes outside the repo entirely, so it is fine from anywhere.
if (cwd === pkgRoot && !isGlobal) {
  console.error(
    "This is the panoply repo itself — there is nothing to install into.\n" +
    "Run `node build.mjs` to regenerate the commands, `node ~/panoply/bin/init.mjs --global`\n" +
    "to install for every project, or run this from another project.",
  );
  process.exit(1);
}

console.log(
  isGlobal
    ? `Installing panoply for every project on this machine${dryRun ? "  (dry run — nothing written)" : ""}`
    : `Installing panoply into ${cwd}${dryRun ? "  (dry run — nothing written)" : ""}`,
);
await onboard();
await checkGithubAuth();
for (const tool of chosen) install(tool);

console.log(
  `\nDone. Reload your agent to pick up the skills (Claude Code), MCP servers and commands` +
  (isGlobal ? ` — in every project, without running this again.` : `.`) +
  `\nNothing is configured yet — the commands run in local mode (report only, no filing, no git) until you ask for more.` +
  (Object.keys(mcpFor(chosen[0])).length ? `\nSee docs/mcp-auth.md for authenticating the GitHub MCP server, or skip it and just use \`gh\`.` : ""),
);
