// `node ~/panoply/bin/init.mjs` skill installs (Claude Code only). Runs the real CLI with
// HOME and cwd pointed at temp dirs, so nothing touches the real ~/.claude or
// this repo.

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, rmSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cli = join(root, "bin", "init.mjs");
const source = join(root, ".claude", "skills");

/** Fresh HOME and project dirs under the OS temp dir. */
function sandbox() {
  const base = mkdtempSync(join(tmpdir(), "panoply-init-"));
  const home = join(base, "home");
  const project = join(base, "project");
  mkdirSync(home);
  mkdirSync(project);
  return { base, home, project };
}

function init(args, { home, project }) {
  const env = { ...process.env, HOME: home };
  delete env.GITHUB_MCP_TOKEN;
  const res = spawnSync(process.execPath, [cli, "init", "--yes", ...args], { cwd: project, env, encoding: "utf8" });
  assert.equal(res.status, 0, res.stderr);
  return res.stdout;
}

describe("init installs skills", () => {
  it("fresh project install copies SKILL.md and a bundled subdirectory file", () => {
    const box = sandbox();
    try {
      const out = init(["--tool", "claude-code"], box);
      const dest = join(box.project, ".claude", "skills");
      assert.match(out, /installed \.claude\/skills\/polyglot\//);
      assert.equal(
        readFileSync(join(dest, "polyglot", "SKILL.md"), "utf8"),
        readFileSync(join(source, "polyglot", "SKILL.md"), "utf8"),
      );
      assert.ok(existsSync(join(dest, "unslop", "references", "signs.md")), "nested subdirectory file copied");
    } finally {
      rmSync(box.base, { recursive: true, force: true });
    }
  });

  it("fresh global install lands in ~/.claude/skills", () => {
    const box = sandbox();
    try {
      init(["--global", "--tool", "claude-code"], box);
      assert.ok(existsSync(join(box.home, ".claude", "skills", "polyglot", "SKILL.md")));
      assert.ok(existsSync(join(box.home, ".claude", "skills", "unslop", "references", "signs.md")));
    } finally {
      rmSync(box.base, { recursive: true, force: true });
    }
  });

  it("does not overwrite a user-authored skill dir (no marker)", () => {
    const box = sandbox();
    try {
      const mine = join(box.project, ".claude", "skills", "polyglot");
      mkdirSync(mine, { recursive: true });
      writeFileSync(join(mine, "SKILL.md"), "---\nname: polyglot\n---\n\nmy own skill\n");
      const out = init(["--tool", "claude-code"], box);
      assert.equal(readFileSync(join(mine, "SKILL.md"), "utf8"), "---\nname: polyglot\n---\n\nmy own skill\n");
      assert.match(out, /skipped skill polyglot/);
      assert.ok(existsSync(join(box.project, ".claude", "skills", "unslop", "SKILL.md")), "other skills still install");
    } finally {
      rmSync(box.base, { recursive: true, force: true });
    }
  });

  it("refreshes a skill dir that carries the generated marker", () => {
    const box = sandbox();
    try {
      const old = join(box.project, ".claude", "skills", "polyglot");
      mkdirSync(old, { recursive: true });
      writeFileSync(join(old, "SKILL.md"), "# GENERATED by build.mjs from skills/polyglot/SKILL.md\nstale\n");
      const out = init(["--tool", "claude-code"], box);
      assert.match(out, /updated \.claude\/skills\/polyglot\//);
      assert.equal(
        readFileSync(join(old, "SKILL.md"), "utf8"),
        readFileSync(join(source, "polyglot", "SKILL.md"), "utf8"),
      );
    } finally {
      rmSync(box.base, { recursive: true, force: true });
    }
  });

  it("--dry-run writes no skills", () => {
    const box = sandbox();
    try {
      init(["--tool", "claude-code", "--dry-run"], box);
      assert.ok(!existsSync(join(box.project, ".claude", "skills")));
    } finally {
      rmSync(box.base, { recursive: true, force: true });
    }
  });
});
